"""Generate sql/yahoo_finance_create.sql from the tickers in src/config.py.

Zetaris REST tables take a fixed endpoint, so each (ticker, interval) gets its
own REST table plus a flattening view. Run:
  .venv/bin/python scripts/gen_yahoo_sql.py
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from src import config  # noqa: E402
from src.integrations.zetaris import (  # noqa: E402
    ZETARIS_INTERVALS,
    bars_view,
    quote_view,
    rest_table,
)

UA = config.YAHOO_UA["User-Agent"]

HEADER = """\
-- =============================================================================
-- Source: Yahoo Finance v8 chart API - US equity/ETF bars and quotes.
-- GENERATED by scripts/gen_yahoo_sql.py from src/config.py - edit the
-- generator, not this file.
--
-- Pattern mirrors zetaris/getting-started 02_pokeapi_create.sql:
-- Lightning database -> schemastore container -> REST table -> views.
--
-- Endpoint (no auth): https://query1.finance.yahoo.com/v8/finance/chart/<T>
--   ?range=<range>&interval=<interval>
-- Yahoo answers 429 to clients without a browser user-agent, so every REST
-- table sends the same user-agent the Python YahooProvider uses.
--
-- Shape: top-level object; chart.result is an array with one element. Bars
-- are PARALLEL ARRAYS (timestamp[], indicators.quote[0].open[] ...), not row
-- objects. The views explode chart.result, then posexplode(timestamp) and
-- index each quote array by that position. Confirmed working 2026-10-20.
--
-- REST tables take a fixed endpoint (no per-query parameters), so there is
-- one REST table per ticker and interval. Every query re-fetches live data
-- from Yahoo. US markets only.
--
-- Coverage:
--   1d / 2y  : watchlist + sector ETFs   (indicator engine, quotes)
--   1wk / 5y : watchlist                 (weekly RSI)
--   5m / 5d  : watchlist                 (intraday bars)
--
-- Run: .venv/bin/python scripts/zsql.py --file sql/yahoo_finance_create.sql --skip-exists
-- =============================================================================

-- Step 0: Lightning database for this source.
CREATE LIGHTNING DATABASE YAHOO_FINANCE_REST DESCRIBE BY "Yahoo Finance chart API - US market data";

-- Step 1: schemastore container.
CREATE SCHEMASTORE CONTAINER yahoo_finance;
"""

# Columns shared by every bars view: symbol, ts (epoch seconds), OHLCV.
BARS_SELECT = """\
SELECT
    r.meta.symbol AS symbol,
    CAST(ts AS BIGINT) AS ts,
    r.indicators.quote[0].open[pos] AS open,
    r.indicators.quote[0].high[pos] AS high,
    r.indicators.quote[0].low[pos] AS low,
    r.indicators.quote[0].close[pos] AS close,
    r.indicators.quote[0].volume[pos] AS volume
FROM yahoo_finance_rest.{table}
LATERAL VIEW explode(chart.result) AS r
LATERAL VIEW posexplode(r.timestamp) AS pos, ts"""

# Quote view: the last two daily bars plus Yahoo's live meta fields, so one
# query (one Yahoo fetch) gives price, previous close and the day's range.
QUOTE_SELECT = """\
SELECT
    r.meta.symbol AS symbol,
    r.meta.regularMarketPrice AS price,
    r.meta.regularMarketDayHigh AS day_high,
    r.meta.regularMarketDayLow AS day_low,
    r.meta.regularMarketVolume AS market_volume,
    r.meta.regularMarketTime AS market_time,
    CAST(ts AS BIGINT) AS ts,
    r.indicators.quote[0].open[pos] AS open,
    r.indicators.quote[0].high[pos] AS high,
    r.indicators.quote[0].low[pos] AS low,
    r.indicators.quote[0].close[pos] AS close,
    r.indicators.quote[0].volume[pos] AS volume
FROM yahoo_finance_rest.{table}
LATERAL VIEW explode(chart.result) AS r
LATERAL VIEW posexplode(r.timestamp) AS pos, ts
WHERE pos >= size(r.timestamp) - 2"""


def rest_table_sql(ticker: str, interval: str) -> str:
    rng = ZETARIS_INTERVALS[interval]
    url = config.YAHOO_CHART_URL.format(ticker=ticker)
    return f"""\
CREATE LIGHTNING REST TABLE {rest_table(ticker, interval)} FROM YAHOO_FINANCE_REST REQUEST(
    endpoint "{url}?range={rng}&interval={interval}",
    method "get",
    response_type "json",
    http_encoding "URLENCODED"
) HEADER (
    user-agent "{UA}"
) BODY ();
"""


def main() -> None:
    daily = list(config.WATCHLIST) + [t for t in config.SECTOR_ETFS if t not in config.WATCHLIST]
    plan = [(t, "1d") for t in daily]
    plan += [(t, "1wk") for t in config.WATCHLIST]
    plan += [(t, "5m") for t in config.WATCHLIST]

    parts = [HEADER]
    for ticker, interval in plan:
        table = rest_table(ticker, interval)
        rng = ZETARIS_INTERVALS[interval]
        parts.append(f"\n-- {ticker} - {interval} bars, {rng}")
        parts.append(rest_table_sql(ticker, interval))
        view = bars_view(ticker, interval).split(".", 1)[1]
        parts.append(
            f"CREATE SCHEMASTORE VIEW {view} WITH CONTAINER yahoo_finance AS\n"
            + BARS_SELECT.format(table=table) + ";\n"
        )
        if interval == "1d":
            qview = quote_view(ticker).split(".", 1)[1]
            parts.append(
                f"CREATE SCHEMASTORE VIEW {qview} WITH CONTAINER yahoo_finance AS\n"
                + QUOTE_SELECT.format(table=table) + ";\n"
            )

    parts.append("""
-- =============================================================================
-- Teardown (commented out). DROP VIEW is the only SQL teardown; REST tables
-- and the Lightning database are removed in the Zetaris Data Explorer.
-- =============================================================================
-- DROP VIEW yahoo_finance.spy_bars_1d;
""")
    out = os.path.join(ROOT, "sql", "yahoo_finance_create.sql")
    with open(out, "w") as fh:
        fh.write("\n".join(parts))
    print(f"wrote {out}: {len(plan)} REST tables")


if __name__ == "__main__":
    main()
