"""Zetaris AI Data Harness integration.

Real REST API details from the official Participant Setup Guide
(saved at docs/hackathon-setup-guide.txt).

Zetaris runs LOCALLY in Docker on the dev machine:
  - Web UI / SQL Editor: http://localhost:3000
  - REST API: http://localhost:8888/api/v1.0
  - API reference: http://localhost:8888/redoc/index.html

Auth on every REST request:
  - Authorization: Bearer <ZETARIS_API_KEY>
  - X-Org-ID: <org id, 1 on a local install>
  - X-Request-ID: fresh UUID per request

Run SQL: POST {ZETARIS_REST_URL}/sql-editor/sqls/run
  body: {"queryId": <uuid>, "sql": "...", "source": "SqlEditor", "limit": N}

What Zetaris gives QuantPilot:
  - A single API over fragmented market-data sources (no ETL): the agent
    queries Zetaris virtual tables instead of hitting Yahoo directly.
  - This is the "fragmented intelligence" story for the judges: one harness
    unifying quotes, bars, chains, breadth and events.

Setup (on the dev laptop, NOT this VM - Zetaris needs 8GB RAM + 15GB disk):
  1. Register at https://cloud.enterprise.zetaris.com/register
  2. Download zetaris-platform.zip + registry credentials from
     https://cloud.enterprise.zetaris.com/dashboard/download
  3. unzip, cd zetaris-platform, docker login zetarishackathon.azurecr.io
  4. ./preflight.sh (fix failures), set ZETARIS_ADMIN_* in .env, chmod 600 .env
  5. docker compose pull && docker compose up -d (30-45 min first start)
  6. ./verify.sh, sign in at http://localhost:3000, create API key in web UI
  7. Register Yahoo Finance as a REST table (see docs/hackathon-setup-guide.txt
     section 1.8 - same pattern as the PokeAPI recipe), then point this
     provider at the Zetaris tables.

Wiring checklist:
  1. Zetaris running locally with API key created in the web UI.
  2. Store the key in the vault (same flow as custom.nvidia).
  3. Register market-data tables in Zetaris (Yahoo REST tables).
  4. Set ZETARIS_REST_URL / ZETARIS_ORG_ID / ZETARIS_API_KEY in .env.
  5. Flip DATA_PROVIDER in src/config.py from "yahoo" to "zetaris".

Market data through Zetaris (wired 2026-10-20):
  - sql/yahoo_finance_create.sql (generated by scripts/gen_yahoo_sql.py)
    registers one Yahoo chart REST table per (ticker, interval) in the
    YAHOO_FINANCE_REST Lightning database, plus flattening views in the
    yahoo_finance container:
      yahoo_finance.<t>_bars_<interval>  symbol, ts, open, high, low, close, volume
      yahoo_finance.<t>_quote            last two daily bars + live price fields
  - Coverage: 1d/2y for the watchlist and sector ETFs, 1wk/5y and 5m/5d for
    the watchlist. Other tickers or intervals raise a table-missing error;
    add them to config and re-run the generator.
  - get_bars() and get_quote() read those views and return the same shapes
    as src/data/yahoo.py.
  - Option chains are NOT in Zetaris yet: get_expirations() and
    get_option_chain() still raise the table-missing error, and options stay
    on the direct Yahoo provider until Day 2 of the build.
"""
from __future__ import annotations

import os
import re
import time
import uuid
from typing import Dict, List, Optional

import pandas as pd
import requests

from ..data.provider import MarketDataProvider

# Intervals registered in Zetaris -> the Yahoo range each REST table fetches.
ZETARIS_INTERVALS = {
    "1d": "2y",
    "1wk": "5y",
    "5m": "5d",
}

# Yahoo period strings -> days, for trimming a stored range to a shorter one.
_PERIOD_DAYS = {
    "1d": 1,
    "5d": 5,
    "1mo": 31,
    "3mo": 92,
    "6mo": 183,
    "1y": 366,
    "2y": 731,
    "5y": 1827,
}

_TICKER_RE = re.compile(r"^[A-Z][A-Z0-9.\-]{0,9}$")

# -- Run-scoped SQL trace -------------------------------------------------
# The demo and the Sponsor Tech score need visible trace lines of the
# Zetaris queries a run actually made. Every run_sql call appends one
# entry here; the runner clears the log at run start and drains it
# into artifacts.json as "data_calls".
# Entries: {"table_or_view", "elapsed_ms", "rows"}. Cache hits in
# CachingProvider never reach this provider, so the trace counts real
# Zetaris calls only.
TRACE_LOG: List[Dict] = []

_FROM_RE = re.compile(r"\bFROM\s+([A-Za-z0-9_.]+)", re.IGNORECASE)


def clear_trace_log() -> None:
    """Start a fresh SQL trace (called at run start)."""
    TRACE_LOG.clear()


def get_trace_log() -> List[Dict]:
    """A copy of the trace lines recorded so far."""
    return [dict(entry) for entry in TRACE_LOG]


def _trace_target(sql: str) -> str:
    """The view a statement reads from (or "ping" when it has no FROM)."""
    match = _FROM_RE.search(sql or "")
    return match.group(1) if match else "ping"


def _table_key(ticker: str) -> str:
    if not _TICKER_RE.match(ticker or ""):
        raise ValueError(f"invalid US ticker: {ticker!r}")
    return ticker.lower().replace(".", "_").replace("-", "_")


def rest_table(ticker: str, interval: str) -> str:
    """Name of the raw Yahoo REST table in YAHOO_FINANCE_REST."""
    return f"{_table_key(ticker)}_chart_{interval}"


def bars_view(ticker: str, interval: str) -> str:
    """Qualified name of the flattened bars view."""
    return f"yahoo_finance.{_table_key(ticker)}_bars_{interval}"


def quote_view(ticker: str) -> str:
    """Qualified name of the quote view (built on the daily table)."""
    return f"yahoo_finance.{_table_key(ticker)}_quote"


def _num(value) -> Optional[float]:
    return None if value is None else float(value)


def _load_api_key() -> str:
    """Load the Zetaris API key without ever hardcoding it.

    Order:
      1. ZETARIS_API_KEY env var (from .env on the Mac)
      2. File named by ZETARIS_API_KEY_FILE env var
      3. Default key file ~/.zetaris-api-key (chmod 600, per setup pack)
    """
    key = os.environ.get("ZETARIS_API_KEY", "").strip()
    if key:
        return key
    key_file = os.environ.get("ZETARIS_API_KEY_FILE", "")
    if not key_file:
        default = os.path.expanduser("~/.zetaris-api-key")
        if os.path.exists(default):
            key_file = default
    if key_file:
        with open(key_file) as fh:
            return fh.read().strip()
    return ""


class ZetarisProvider(MarketDataProvider):
    """MarketDataProvider backed by a local Zetaris install via its REST API."""

    def __init__(
        self,
        rest_url: str = "http://localhost:8888/api/v1.0",
        org_id: str = "1",
        api_key: str = "",
        options_provider: Optional[MarketDataProvider] = None,
    ) -> None:
        self.rest_url = rest_url.rstrip("/")
        self.org_id = org_id
        self.api_key = api_key
        # Option chains (and earnings dates) are not Zetaris tables yet.
        # When set, those calls go to this provider (direct Yahoo in the
        # factory); when None they raise the table-missing error.
        self.options_provider = options_provider

    @classmethod
    def from_env(
        cls, options_provider: Optional[MarketDataProvider] = None
    ) -> "ZetarisProvider":
        """Build a provider from .env / environment settings."""
        return cls(
            rest_url=os.environ.get(
                "ZETARIS_REST_URL", "http://localhost:8888/api/v1.0"
            ),
            org_id=os.environ.get("ZETARIS_ORG_ID", "1"),
            api_key=_load_api_key(),
            options_provider=options_provider,
        )

    def _headers(self) -> dict:
        return {
            "Authorization": "Bearer " + self.api_key,
            "X-Org-ID": self.org_id,
            "X-Request-ID": str(uuid.uuid4()),
        }

    def run_sql(self, sql: str, limit: int = 1000) -> list:
        """Run one SQL statement against Zetaris, return rows as lists.

        Each call (success or failure) appends a trace line to the
        module TRACE_LOG: the view read, wall-clock ms, row count.
        """
        started = time.time()
        rows: list = []
        try:
            resp = requests.post(
                self.rest_url + "/sql-editor/sqls/run",
                headers=self._headers(),
                json={
                    "queryId": str(uuid.uuid4()),
                    "sql": sql,
                    "source": "SqlEditor",
                    "limit": limit,
                },
                timeout=60,
            )
            resp.raise_for_status()
            rows = resp.json().get("data", [])
            return rows
        finally:
            TRACE_LOG.append(
                {
                    "table_or_view": _trace_target(sql),
                    "elapsed_ms": int(round((time.time() - started) * 1000)),
                    "rows": len(rows),
                }
            )

    def ping(self) -> bool:
        """True when Zetaris answers SQL."""
        rows = self.run_sql("SELECT 1 AS one", limit=1)
        return bool(rows) and str(rows[0][0]) == "1"

    # -- MarketDataProvider interface -------------------------------------
    # Bars and quotes read the yahoo_finance views created by
    # sql/yahoo_finance_create.sql. Option chains are not registered yet.

    def _table_missing(self, table: str) -> NotImplementedError:
        return NotImplementedError(
            f"Zetaris table '{table}' is not registered yet. "
            "Add the ticker/interval to src/config.py, regenerate "
            "sql/yahoo_finance_create.sql with scripts/gen_yahoo_sql.py "
            "and run it against Zetaris."
        )

    def _query_view(self, view: str, sql: str, limit: int) -> list:
        try:
            return self.run_sql(sql, limit=limit)
        except requests.HTTPError as error:
            body = error.response.text.lower() if error.response is not None else ""
            if "not found" in body or "cannot be found" in body or "not exist" in body:
                raise self._table_missing(view) from error
            raise

    def get_quote(self, ticker: str) -> dict:
        view = quote_view(ticker)
        rows = self._query_view(
            view,
            "SELECT price, day_high, day_low, ts, open, high, low, close, volume "
            f"FROM {view} ORDER BY ts",
            limit=10,
        )
        if not rows:
            raise ValueError(f"no quote data in Zetaris for {ticker}")
        last = rows[-1]
        # Yahoo can leave the newest daily bar's close null (premarket /
        # after hours); the previous close is the last non-null close
        # BEFORE the newest bar, never the newest bar itself.
        prior = [r for r in rows[:-1] if r[7] is not None]
        prev_close = _num(prior[-1][7]) if prior else None
        if prev_close is None:
            # In the session the quote view can hold only today's row
            # (measured live Oct 22: every quote came back with no
            # previous close). The last completed daily bar before
            # today's is the previous close.
            prev_close = self._prior_daily_close(ticker, int(float(last[3])))
        price = _num(last[0]) or _num(last[7])
        if price is None:
            raise ValueError(f"no price in Zetaris quote for {ticker}")
        change = (price - prev_close) if prev_close else None
        return {
            "ticker": ticker,
            "price": float(price),
            "change": float(change) if change is not None else None,
            "change_pct": float(change / prev_close * 100) if prev_close else None,
            "volume": int(float(last[8] or 0)),
            "day_high": float(_num(last[1]) or _num(last[5])),
            "day_low": float(_num(last[2]) or _num(last[6])),
            "open": float(_num(last[4])),
            "previous_close": float(prev_close) if prev_close else None,
        }

    def _prior_daily_close(self, ticker: str, before_ts: int) -> Optional[float]:
        """Close of the newest 1d bar strictly before before_ts, or None."""
        try:
            view = bars_view(ticker, "1d")
            rows = self._query_view(
                view,
                f"SELECT ts, close FROM {view} WHERE ts < {int(before_ts) - 3600} "
                "AND close IS NOT NULL ORDER BY ts DESC",
                limit=1,
            )
        except Exception:
            return None
        return _num(rows[0][1]) if rows else None

    def get_bars(
        self,
        ticker: str,
        interval: str = "1d",
        period: str = "2y",
    ) -> pd.DataFrame:
        if interval not in ZETARIS_INTERVALS:
            raise self._table_missing(f"{_table_key(ticker)}_bars_{interval}")
        stored = ZETARIS_INTERVALS[interval]
        period = period or stored
        if _PERIOD_DAYS.get(period, 10**6) > _PERIOD_DAYS[stored]:
            raise ValueError(
                f"Zetaris holds {stored} of {interval} bars; period {period} is longer"
            )
        view = bars_view(ticker, interval)
        sql = f"SELECT ts, open, high, low, close, volume FROM {view}"
        if period != stored:
            cutoff = int(time.time()) - _PERIOD_DAYS[period] * 86400
            sql += f" WHERE ts >= {cutoff}"
        rows = self._query_view(view, sql + " ORDER BY ts", limit=100000)
        df = pd.DataFrame(
            {
                "open": [_num(r[1]) for r in rows],
                "high": [_num(r[2]) for r in rows],
                "low": [_num(r[3]) for r in rows],
                "close": [_num(r[4]) for r in rows],
                "volume": [_num(r[5]) for r in rows],
            },
            index=pd.to_datetime([int(r[0]) for r in rows], unit="s", utc=True),
        )
        df.index.name = "timestamp"
        return df.dropna(subset=["close"])

    def get_expirations(self, ticker: str) -> List[int]:
        if self.options_provider is not None:
            return self.options_provider.get_expirations(ticker)
        raise self._table_missing("option_expirations")

    def get_option_chain(
        self,
        ticker: str,
        expiration: Optional[int] = None,
    ) -> Dict[str, List[dict]]:
        if self.options_provider is not None:
            return self.options_provider.get_option_chain(
                ticker, expiration=expiration
            )
        raise self._table_missing("option_chains")

    def get_earnings_date(self, ticker: str):
        """Next earnings date via the options provider, else None."""
        getter = getattr(self.options_provider, "get_earnings_date", None)
        return getter(ticker) if getter is not None else None
